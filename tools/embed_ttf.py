"""Emit the TTFs as C byte arrays, for boards that can rasterise an outline at runtime.

On an ESP32-S3 class part (the SenseCAP Indicator, for one) LVGL 9's lv_tiny_ttf, or
LVGL 8 with the lv_lib_freetype binding, will render a real outline at any size. That
needs the font file in memory; this puts it in flash as a const array so there is no
filesystem to provision.

    python tools/embed_ttf.py [dist_dir]
"""

import os
import sys

import stroke

STYLES = ("Regular", "Bold")


def main():
    dist = sys.argv[1] if len(sys.argv) > 1 else os.path.join(stroke.ROOT, "dist")
    out = os.path.join(dist, "ttf_c")
    os.makedirs(out, exist_ok=True)
    c, h = [], []
    note = ("Deflect Stencil TTFs as C arrays -- public domain (CC0 1.0). "
            "Generated by tools/embed_ttf.py; do not edit by hand.")
    c.append("/* %s */" % note)
    c.append('#include "deflect_stencil_ttf.h"')
    c.append("")
    h.append("/* %s */" % note)
    h.append("/*")
    h.append(" * LVGL 9:   lv_font_t *f = lv_tiny_ttf_create_data(")
    h.append(" *               deflect_stencil_regular_ttf,")
    h.append(" *               deflect_stencil_regular_ttf_len, 24);")
    h.append(" * Ask for a size in pixels; tiny_ttf treats it as the em, and this")
    h.append(" * design puts the capital height at 0.70 em to the stroke centre")
    h.append(" * (0.75 em to its outer edge at Regular), so a 24 px em gives a")
    h.append(" * capital about 18 px tall.")
    h.append(" */")
    h.append("#ifndef DEFLECT_STENCIL_TTF_H")
    h.append("#define DEFLECT_STENCIL_TTF_H")
    h.append("")
    h.append("#include <stddef.h>")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append('extern "C" {')
    h.append("#endif")
    h.append("")
    for style in STYLES:
        data = open(os.path.join(dist, "ttf", "DeflectStencil-%s.ttf" % style), "rb").read()
        ident = "deflect_stencil_%s_ttf" % style.lower()
        h.append("extern const uint8_t %s[%d];" % (ident, len(data)))
        h.append("#define %s_len %d" % (ident, len(data)))
        c.append("const uint8_t %s[%d] = {" % (ident, len(data)))
        for i in range(0, len(data), 16):
            c.append("    " + " ".join("0x%02X," % b for b in data[i:i + 16]))
        c.append("};")
        c.append("")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif /* DEFLECT_STENCIL_TTF_H */")
    for name, lines in (("deflect_stencil_ttf.c", c), ("deflect_stencil_ttf.h", h)):
        with open(os.path.join(out, name), "w", encoding="ascii", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
    print("ttf_c/deflect_stencil_ttf.c + .h")


if __name__ == "__main__":
    main()
