"""Build the bitmap fonts in every format, at every size.

    python tools/build_bitmap.py [out_dir]

Writes, per size: a BDF, an Adafruit_GFX header and an LVGL C font; plus one pair of
u8g2 C files holding all sizes. Each u8g2 font is decoded again before it is written,
with the decoder that was checked against u8g2's own font, so what ships is known to
read back pixel for pixel.
"""

import os
import sys

import bitmap
import fmt_bdf
import fmt_gfx
import fmt_lvgl
import fmt_u8g2
import stroke
from stroke import WEIGHTS

# Capital heights in pixels, ink included. Bold needs the room for a wider stroke to
# tell it apart from Regular, so it starts at 8.
CAPS = {"Regular": [6, 8, 10, 12, 16, 20, 24], "Bold": [8, 10, 12, 16, 20, 24]}

NOTE = ("Deflect Stencil -- public domain (CC0 1.0). Generated by "
        "tools/build_bitmap.py; do not edit by hand.")


def code_map(limit=None):
    out = {}
    for name, info in stroke.GLYPHS.items():
        for cp in info["codepoints"]:
            if limit is None or cp <= limit:
                out[cp] = name
    return dict(sorted(out.items()))


def ident_for(style, cap):
    return "deflect_stencil_%d%s" % (cap, "b" if style == "Bold" else "")


def gfx_ident(style, cap):
    return "DeflectStencil%d%s" % (cap, "Bold" if style == "Bold" else "")


def render_size(style, cap):
    size = bitmap.Size(cap, WEIGHTS[style][0])
    names = [n for n in stroke.GLYPHS if stroke.GLYPHS[n]["codepoints"]]
    return size, {n: bitmap.render(n, size) for n in names}


def line_metrics(cap):
    """Ascent, descent and line height shared by both weights at this size, so a
    switch from Regular to Bold does not move the baseline."""
    asc = desc = 0
    for style in ("Regular", "Bold"):
        if cap not in CAPS[style]:
            continue
        a, d = bitmap.ascent_descent(render_size(style, cap)[1])
        asc, desc = max(asc, a), max(desc, d)
    return asc, desc, asc + desc + max(1, round(cap / 5.0))


def build_size(style, cap, out_dir, u8g2_parts):
    size, rasters = render_size(style, cap)
    asc, desc, line_height = line_metrics(cap)

    all_codes = code_map()
    ascii_codes = {cp: n for cp, n in all_codes.items() if 0x20 <= cp <= 0x7E}
    byte_codes = {cp: n for cp, n in all_codes.items() if cp <= 0xFF}

    # ---- BDF ------------------------------------------------------------
    bdf_dir = os.path.join(out_dir, "bdf")
    os.makedirs(bdf_dir, exist_ok=True)
    bdf_path = os.path.join(bdf_dir, "DeflectStencil-%s-%d.bdf" % (style, cap))
    fmt_bdf.write(
        bdf_path, rasters, sorted(all_codes.items()), cap, size.stroke,
        "Bold" if style == "Bold" else "Medium", asc, desc, NOTE,
    )

    # ---- Adafruit_GFX ---------------------------------------------------
    gfx_dir = os.path.join(out_dir, "gfx")
    os.makedirs(gfx_dir, exist_ok=True)
    gid = gfx_ident(style, cap)
    gfx_bytes = fmt_gfx.write(
        os.path.join(gfx_dir, "%s.h" % gid), gid, rasters, ascii_codes,
        line_height, cap, size.stroke, NOTE,
    )

    # ---- LVGL -----------------------------------------------------------
    lv_dir = os.path.join(out_dir, "lvgl")
    os.makedirs(lv_dir, exist_ok=True)
    lid = ident_for(style, cap)
    lv_bytes = fmt_lvgl.write(
        os.path.join(lv_dir, "%s.c" % lid), lid, rasters, all_codes,
        line_height, desc, cap, size.stroke, NOTE,
    )

    # ---- u8g2 (collected, written once at the end) ----------------------
    glyphs = sorted(((cp, rasters[n]) for cp, n in byte_codes.items()))
    a_raster = rasters["A"]
    data = fmt_u8g2.encode(
        glyphs,
        ascent_A=a_raster.yoff + a_raster.h,
        descent_g=-desc,
        ascent_para=asc,
        descent_para=-desc,
    )
    roundtrip(data, glyphs, "%s %d" % (style, cap))
    u8g2_parts.append((ident_for(style, cap), data, cap, size.stroke, asc, desc))

    return dict(
        style=style, cap=cap, stroke=size.stroke, asc=asc, desc=desc,
        line=line_height, bdf=os.path.getsize(bdf_path), gfx=gfx_bytes,
        lvgl=lv_bytes, u8g2=len(data),
    )


def roundtrip(data, glyphs, label):
    info = fmt_u8g2.read_info(data)
    for enc, r in glyphs:
        got = fmt_u8g2.decode_glyph(data, info, enc)
        if got is None:
            raise SystemExit("u8g2 %s: glyph %d vanished" % (label, enc))
        grid, w, h, x, y, d = got
        if d != r.advance:
            raise SystemExit("u8g2 %s: glyph %d advance %d != %d" % (label, enc, d, r.advance))
        if not r.w:
            if w:
                raise SystemExit("u8g2 %s: glyph %d should be blank" % (label, enc))
            continue
        if (w, h, x, y) != (r.w, r.h, r.xoff, r.yoff) or grid != r.bits:
            raise SystemExit("u8g2 %s: glyph %d does not read back" % (label, enc))


def write_u8g2(out_dir, parts):
    d = os.path.join(out_dir, "u8g2")
    os.makedirs(d, exist_ok=True)
    c, h = [], []
    c.append("/* %s */" % NOTE)
    c.append('#include "deflect_stencil_u8g2.h"')
    c.append("")
    c.append("/* u8g2 puts fonts in a named section on AVR; elsewhere this is a no-op. */")
    c.append("#ifndef U8G2_FONT_SECTION")
    c.append("#define U8G2_FONT_SECTION(name)")
    c.append("#endif")
    c.append("")
    h.append("/* %s */" % NOTE)
    h.append("#ifndef DEFLECT_STENCIL_U8G2_H")
    h.append("#define DEFLECT_STENCIL_U8G2_H")
    h.append("")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append('extern "C" {')
    h.append("#endif")
    h.append("")
    h.append("/* Capital height in px (ink included) / stroke / ascent / descent:")
    for ident, data, cap, stroke_px, asc, desc in parts:
        h.append("     %-24s cap %2d  stroke %d  asc %2d  desc %d  %5d bytes"
                 % (ident, cap, stroke_px, asc, desc, len(data)))
    h.append(" */")
    h.append("")
    for ident, data, cap, stroke_px, asc, desc in parts:
        h.append("extern const uint8_t %s[%d];" % (ident, len(data)))
        c.append("/* cap %d px, stroke %d px, ascent %d, descent %d, %d bytes */"
                 % (cap, stroke_px, asc, desc, len(data)))
        c.append("const uint8_t %s[%d] U8G2_FONT_SECTION(\"%s\") = {"
                 % (ident, len(data), ident))
        for i in range(0, len(data), 16):
            c.append("    " + " ".join("0x%02X," % b for b in data[i:i + 16]))
        c.append("};")
        c.append("")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif /* DEFLECT_STENCIL_U8G2_H */")
    with open(os.path.join(d, "deflect_stencil_u8g2.c"), "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(c) + "\n")
    with open(os.path.join(d, "deflect_stencil_u8g2.h"), "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(h) + "\n")


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(stroke.ROOT, "dist")
    parts, report = [], []
    for style in ("Regular", "Bold"):
        for cap in CAPS[style]:
            report.append(build_size(style, cap, out_dir, parts))
    write_u8g2(out_dir, parts)

    print("flash footprint per size, in bytes (tables included):")
    print("%-8s %3s %6s %4s %5s %6s %7s %7s %7s"
          % ("style", "cap", "stroke", "asc", "desc", "line", "u8g2", "gfx", "lvgl"))
    for r in report:
        print("%-8s %3d %6d %4d %5d %6d %7d %7d %7d"
              % (r["style"], r["cap"], r["stroke"], r["asc"], r["desc"], r["line"],
                 r["u8g2"], r["gfx"], r["lvgl"]))
    print("\n%d sizes; every u8g2 font decoded back to the exact pixels." % len(report))


if __name__ == "__main__":
    main()
