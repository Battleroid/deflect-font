GAP = 1.3


def layout(s, size, spacing=1.0, slant=0.0):
	"""Returns (polylines in pixels relative to the pen at the baseline, total width)."""
	unit = size / 6.0
	pen = 0.0
	lines = []
	for ch in s.upper():
		width, strokes = GLYPHS.get(ch, GLYPHS[" "])
		for stroke in strokes:
			lines.append([((pen + x) * unit + y * unit * slant, -y * unit) for x, y in stroke])
		pen += width + GAP * spacing
	total = max(0.0, pen - GAP * spacing) * unit
	return lines, total


def text_width(s, size, spacing=1.0):
	return layout(s, size, spacing)[1]


